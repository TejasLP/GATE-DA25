import os
import sys
from pathlib import Path
import matplotlib.pyplot as plt
import numpy as np

# Resolve project root and CoordGeo paths relative to codes/q9/q9.py
script_dir = Path(__file__).resolve().parent
project_root = script_dir.parents[1]  # GATE-DA25/
coordgeo_dir = project_root / "codes" / "CoordGeo"

# Add CoordGeo paths to sys.path
sys.path.insert(0, str(coordgeo_dir))
sys.path.insert(0, str(coordgeo_dir / "line"))
sys.path.insert(0, str(coordgeo_dir / "plotting"))

# Import custom functions from CoordGeo
from line.funcs import line_gen

# Resolve the root figs directory
fig_dir = project_root / "figs"
fig_dir.mkdir(parents=True, exist_ok=True)

# Define parameter t (derived from median = 3)
t = 2.0

# --- Load simulation data generated by C code ---
dat_path = script_dir / "uniform_samples.dat"
if dat_path.exists():
    data = np.loadtxt(dat_path)
    if data.ndim == 1:
        data = data.reshape(1, -1)
    u_vals = data[:, 0]
    x_sim = data[:, 1]
else:
    # Fallback if C code hasn't been run yet (500 samples)
    np.random.seed(42)
    u_vals = np.random.uniform(0, 1, 500)
    x_sim = 2.0 * u_vals + 2.0

# --- Generate CDF components using line_gen ---
A_cdf_left = np.array([[0.0], [0.0]])
B_cdf_left = np.array([[t], [0.0]])
cdf_left_seg = line_gen(A_cdf_left, B_cdf_left)

A_cdf_mid = np.array([[t], [0.0]])
B_cdf_mid = np.array([[4.0], [1.0]])
cdf_mid_seg = line_gen(A_cdf_mid, B_cdf_mid)

A_cdf_right = np.array([[4.0], [1.0]])
B_cdf_right = np.array([[6.0], [1.0]])
cdf_right_seg = line_gen(A_cdf_right, B_cdf_right)

# --- Generate PDF components using line_gen ---
A_pdf_left = np.array([[0.0], [0.0]])
B_pdf_left = np.array([[t], [0.0]])
pdf_left_seg = line_gen(A_pdf_left, B_pdf_left)

A_pdf_mid = np.array([[t], [0.5]])
B_pdf_mid = np.array([[4.0], [0.5]])
pdf_mid_seg = line_gen(A_pdf_mid, B_pdf_mid)

A_pdf_right = np.array([[4.0], [0.0]])
B_pdf_right = np.array([[6.0], [0.0]])
pdf_right_seg = line_gen(A_pdf_right, B_pdf_right)

# ==========================================
# Figure 1: CDF Plot (Saved Separately)
# ==========================================
fig1, ax1 = plt.subplots(figsize=(8, 5))

ax1.plot(cdf_left_seg[0, :], cdf_left_seg[1, :], color="blue", lw=2)
ax1.plot(
    cdf_mid_seg[0, :],
    cdf_mid_seg[1, :],
    color="blue",
    lw=2,
    label="Theoretical CDF",
)
ax1.plot(cdf_right_seg[0, :], cdf_right_seg[1, :], color="blue", lw=2)

x_sorted = np.sort(x_sim)
y_empirical = np.arange(1, len(x_sorted) + 1) / len(x_sorted)
ax1.step(
    x_sorted,
    y_empirical,
    color="red",
    linestyle="--",
    lw=1.2,
    label="Simulated CDF (Simulation, n=500)",
)

ax1.set_title("Cumulative Distribution Function (CDF)")
ax1.set_xlabel("$x$")
ax1.set_ylabel("$F_X(x)$")
ax1.set_xlim(-0.2, 6.2)
ax1.set_ylim(-0.1, 1.1)
ax1.grid(True)
ax1.legend()

fig1.tight_layout()
cdf_output_path = fig_dir / "cdf_distribution_q9.pdf"
fig1.savefig(cdf_output_path, format="pdf", bbox_inches="tight")
plt.close(fig1)

# ==========================================
# Figure 2: PDF Plot (Saved Separately)
# ==========================================
fig2, ax2 = plt.subplots(figsize=(8, 5))

ax2.plot(pdf_left_seg[0, :], pdf_left_seg[1, :], color="red", lw=2)
ax2.plot(
    pdf_mid_seg[0, :],
    pdf_mid_seg[1, :],
    color="red",
    lw=2,
    label="Theoretical PDF ($f_X(x) = 0.5$)",
)
ax2.plot(pdf_right_seg[0, :], pdf_right_seg[1, :], color="red", lw=2)

ax2.set_title("Probability Density Function (PDF - Theoretical)")
ax2.set_xlabel("$x$")
ax2.set_ylabel("$f_X(x)$")
ax2.set_xlim(-0.2, 6.2)
ax2.set_ylim(-0.1, 0.8)
ax2.grid(True)
ax2.legend()

fig2.tight_layout()
pdf_output_path = fig_dir / "pdf_distribution_q9.pdf"
fig2.savefig(pdf_output_path, format="pdf", bbox_inches="tight")
plt.close(fig2)

print(f"Successfully saved CDF plot to {cdf_output_path}")
print(f"Successfully saved PDF plot to {pdf_output_path}")
